/* Read current from ACS758LCB-050B (powered at 3.3V) */
float read_current(void)
{
    uint32_t sum = 0;

    for(int i = 0; i < 10; i++)
    {
        HAL_ADC_Start(&hadc1);
        HAL_ADC_PollForConversion(&hadc1, 100);
        sum += HAL_ADC_GetValue(&hadc1);
        HAL_ADC_Stop(&hadc1);
    }

    float adc_value = sum / 10.0f;

    float vout = (adc_value * 3.3f) / 4095.0f;
    float zero_current = 1.65f;
    float sensitivity  = 0.0264f;

    float current_A = (vout - zero_current) / sensitivity;

    return current_A;
}

